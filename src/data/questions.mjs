function applyScoringMetadata(question, questionIndex) {
  const scoringOptions = scoringOptionSets[questionIndex % scoringOptionSets.length];
  return {
    ...question,
    chapter: Math.floor(questionIndex / 6) + 1,
    options: question.options.map((option, optionIndex) => ({
      ...option,
      poles: option.poles ?? scoringOptions[optionIndex].poles,
    })),
  };
}

